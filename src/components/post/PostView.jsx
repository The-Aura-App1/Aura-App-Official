// Post and comment ids are generated by the server as `<ms>-<base36>`. Anything
// else in the address can't be a real post, so it's never sent to the API.
const ID_PATTERN = /^[A-Za-z0-9_-]{1,64}$/;

// Same limits the server enforces (aura-comments): Instagram-length for the
// main feed, Reddit-length in groups.
const LIMIT_GLOBAL = 2200;
const LIMIT_GROUP  = 10000;
const PAGE = 50;
const MAX_PAGE = 200;

const REPORT_REASONS = [
  ['spam', 'Spam or scam'],
  ['harassment', 'Harassment or bullying'],
  ['hate', 'Hate or violence'],
  ['other', 'Something else'],
];

function profileLink(username) {
  return `/profile/${encodeURIComponent(username ?? '')}`;
}

const MEDIA_URL = 'https://aura-app-media-570934198135.s3.amazonaws.com/';

// Profile picture, or the first letter of the name when there isn't one (or it fails to load)
function Avatar({ name, picKey, size = 'w-8 h-8' }) {
  const [broken, setBroken] = useState(false);
  const showPic = picKey && !broken;
  return (
    <span className={`${size} aura-avatar rounded-full flex-shrink-0 overflow-hidden flex items-center justify-center
                      bg-aura-500/15 border border-aura-500/25 text-aura-400 text-xs font-bold`}>
      {showPic
        ? <img src={MEDIA_URL + picKey} alt="" className="w-full h-full object-cover" onError={() => setBroken(true)} />
        : (name?.[0]?.toUpperCase() ?? '?')}
    </span>
  );
}

// Closes a pop-up menu on a click outside it or on Escape
function useDismiss(open, close) {
  const ref = useRef(null);
  useEffect(() => {
    if (!open) return undefined;
    const onDown = e => { if (ref.current && !ref.current.contains(e.target)) close(); };
    const onKey  = e => { if (e.key === 'Escape') close(); };
    document.addEventListener('pointerdown', onDown);
    document.addEventListener('keydown', onKey);
    return () => {
      document.removeEventListener('pointerdown', onDown);
      document.removeEventListener('keydown', onKey);
    };
  }, [open, close]);
  return ref;
}

// A text box that grows with what's typed, with a character count near the limit.
function Composer({ limit, placeholder, submitLabel, autoFocus, onSubmit, onCancel, inputRef }) {
  const [text, setText]       = useState('');
  const [sending, setSending] = useState(false);
  const [error, setError]     = useState('');
  const left = limit - text.length;

  async function submit() {
    const trimmed = text.trim();
    if (!trimmed || sending || left < 0) return;
    setSending(true);
    setError('');
    try {
      await onSubmit(trimmed);
      setText('');
    } catch (err) {
      setError(err.message || 'Could not post your comment.');
    } finally {
      setSending(false);
    }
  }

  return (
    <div>
      <textarea
        ref={inputRef}
        value={text}
        autoFocus={autoFocus}
        onChange={e => { setText(e.target.value); setError(''); }}
        onKeyDown={e => { if (e.key === 'Enter' && (e.metaKey || e.ctrlKey)) submit(); }}
        placeholder={placeholder}
        rows={2}
        maxLength={limit + 200}
        aria-label={placeholder}
        className="input min-h-[2.75rem] resize-y text-sm leading-relaxed"
      />
      <div className="mt-2 flex items-center justify-end gap-3">
        {left < 200 && (
          <span className={`text-xs tabular-nums ${left < 0 ? 'text-red-400' : 'text-[var(--text-muted)]'}`}>
            {left}
          </span>
        )}
        {error && <span className="mr-auto text-xs text-red-400">{error}</span>}
        {onCancel && (
          <button onClick={onCancel} className="text-xs font-semibold text-[var(--text-muted)] hover:text-[var(--text-primary)]">
            Cancel
          </button>
        )}
        <button
          onClick={submit}
          disabled={sending || !text.trim() || left < 0}
          className="btn-primary px-4 py-2 text-xs disabled:opacity-50">
          {sending ? 'Posting...' : submitLabel}
        </button>
      </div>
    </div>
  );
}

function Comment({ comment, post, isReply, onReply, onDeleted, onAura }) {
  const { user, dbProfile } = useAuth();
  const isMine = user?.userId === comment.authorId;
  // The server says who may delete; authors and moderators always can (it checks again anyway)
  const canDelete = comment.canDelete ?? (isMine || !!dbProfile?.isAdmin);
  // Your own comments show your current picture straight away
  const picKey = comment.authorPicKey || (isMine ? dbProfile?.profilePicKey : '');
  const [liked, setLiked]         = useState(!!comment.likedByMe);
  const [likeCount, setLikeCount] = useState(comment.likeCount);
  const [liking, setLiking]       = useState(false);
  const [menuOpen, setMenuOpen]   = useState(false);
  const [confirmDelete, setConfirmDelete] = useState(false);
  const [reporting, setReporting] = useState(false);
  const [notice, setNotice]       = useState('');
  const [busy, setBusy]           = useState(false);
  const closeMenu = useCallback(() => { setMenuOpen(false); setConfirmDelete(false); setReporting(false); }, []);
  const menuRef = useDismiss(menuOpen, closeMenu);

  async function toggleLike() {
    if (liking) return;
    const next = !liked;
    setLiking(true);
    setLiked(next);
    if (likeCount !== undefined) setLikeCount(c => c + (next ? 1 : -1));
    try {
      await (next ? api.likeComment(comment.commentId) : api.unlikeComment(comment.commentId));
    } catch {
      setLiked(!next);
      if (likeCount !== undefined) setLikeCount(c => c + (next ? -1 : 1));
    } finally {
      setLiking(false);
    }
  }

  async function remove() {
    if (!confirmDelete) { setConfirmDelete(true); return; }
    setBusy(true);
    try {
      await api.deleteComment(comment.commentId);
      onDeleted(comment);
    } catch (err) {
      setNotice(err.message || 'Could not delete the comment.');
      setBusy(false);
      setConfirmDelete(false);
    }
  }

  async function report(reason) {
    setBusy(true);
    try {
      await api.reportComment(comment.commentId, reason);
      setNotice('Thanks. Our moderators will take a look.');
    } catch (err) {
      setNotice(err.message || 'Could not send the report.');
    } finally {
      setBusy(false);
      setReporting(false);
      setMenuOpen(false);
    }
  }

  return (
    <div className="flex gap-3">
      <Link to={profileLink(comment.authorUsername)} aria-label={`@${comment.authorUsername}`}>
        <Avatar name={comment.authorDisplay || comment.authorUsername} picKey={picKey} size={isReply ? 'w-7 h-7' : 'w-8 h-8'} />
      </Link>
      <div className="min-w-0 flex-1">
        <div className="flex items-start gap-2">
          <p className="min-w-0 flex-1 text-xs text-[var(--text-muted)] truncate">
            <Link to={profileLink(comment.authorUsername)}
              className="font-semibold text-sm text-[var(--text-primary)] hover:text-[var(--accent)]">
              {comment.authorDisplay || comment.authorUsername}
            </Link>
            <span className="ml-1.5">@{comment.authorUsername}</span>
            <span aria-hidden="true"> · </span>
            <time dateTime={comment.createdAt}>{timeAgo(comment.createdAt)}</time>
          </p>
          {(canDelete || !isMine) && <div ref={menuRef} className="relative -mt-1">
            <button
              onClick={() => (menuOpen ? closeMenu() : setMenuOpen(true))}
              aria-label="Comment options" aria-expanded={menuOpen}
              className="p-1.5 rounded-lg text-[var(--text-muted)] hover:bg-[var(--accent-subtle)] hover:text-[var(--accent)]">
              <MoreHorizontal size={16} />
            </button>
            {menuOpen && (
              <div className="absolute right-0 top-full mt-1 z-20 min-w-[12rem] rounded-xl p-1
                              bg-[var(--bg-secondary)] border border-[var(--border)] shadow-lg">
                {canDelete && (
                  <button onClick={remove} disabled={busy}
                    className="w-full flex items-center gap-2 text-left px-3 py-2 rounded-lg text-sm text-red-400 hover:bg-red-400/10 disabled:opacity-50">
                    <Trash2 size={14} />
                    {busy ? 'Deleting...' : confirmDelete ? 'Tap again to delete' : isMine ? 'Delete comment' : 'Remove comment'}
                  </button>
                )}
                {!isMine && (reporting ? (
                  <div className="p-1">
                    <p className="px-2 pb-1 text-xs text-[var(--text-muted)]">What's wrong with it?</p>
                    {REPORT_REASONS.map(([value, label]) => (
                      <button key={value} onClick={() => report(value)} disabled={busy}
                        className="w-full text-left px-2 py-1.5 rounded-lg text-sm text-[var(--text-primary)] hover:bg-[var(--accent-subtle)] disabled:opacity-50">
                        {label}
                      </button>
                    ))}
                  </div>
                ) : (
                  <button onClick={() => setReporting(true)}
                    className="w-full flex items-center gap-2 text-left px-3 py-2 rounded-lg text-sm text-[var(--text-primary)] hover:bg-[var(--accent-subtle)]">
                    <Flag size={14} /> Report comment
                  </button>
                ))}
              </div>
            )}
          </div>}
        </div>

        {/* Plain text only: React escapes it, and nothing here is ever rendered as HTML */}
        <p className="mt-0.5 text-sm leading-relaxed text-[var(--text-primary)] whitespace-pre-wrap break-words">
          {comment.text}
        </p>

        <div className="mt-1.5 flex items-center gap-1 text-xs">
          <button onClick={() => onAura(comment, 'give')} disabled={isMine}
            title={isMine ? "You can't give aura to your own comment" : 'Give aura'}
            className="flex items-center gap-1 px-2 py-1 rounded-lg font-semibold text-aura-400 hover:bg-aura-500/10 disabled:opacity-40 disabled:hover:bg-transparent">
            <Sparkles size={12} /> Give
          </button>
          <AuraScore value={comment.auraScore ?? 0} className="px-1" />
          {post.allowTakes !== false && !isMine && (
            <button onClick={() => onAura(comment, 'take')}
              className="px-2 py-1 rounded-lg font-semibold text-red-400 hover:bg-red-500/10">
              Take
            </button>
          )}
          <button onClick={toggleLike} disabled={liking} aria-pressed={liked} aria-label={liked ? 'Unlike comment' : 'Like comment'}
            className={`ml-1 flex items-center gap-1 px-2 py-1 rounded-lg ${liked ? 'text-red-400' : 'text-[var(--text-muted)] hover:text-red-400 hover:bg-red-400/10'}`}>
            <LikeHeart liked={liked} size={13} />
            {likeCount !== undefined && <span className="tabular-nums">{likeCount}</span>}
          </button>
          {!isReply && (
            <button onClick={() => onReply(comment)}
              className="flex items-center gap-1 px-2 py-1 rounded-lg font-semibold text-[var(--text-muted)] hover:text-[var(--accent)] hover:bg-[var(--accent-subtle)]">
              <CornerDownRight size={12} /> Reply
            </button>
          )}
        </div>
        {notice && <p className="mt-1 text-xs text-[var(--text-muted)]">{notice}</p>}
      </div>
    </div>
  );
}

function NotFound() {
  return (
    <div className="card p-8 text-center">
      <h1 className="text-xl font-bold text-[var(--text-primary)]">This post isn't available</h1>
      <p className="mt-2 text-sm text-[var(--text-muted)]">
        It may have been deleted, or it's in a group you're not a member of.
      </p>
      <Link to="/" className="btn-primary inline-flex mt-5 px-5 py-2.5 text-sm">Back to your feed</Link>
    </div>
  );
}

// A single post with its comments: give and take aura, like, reply (one level
// deep), delete your own, report other people's. Everything is checked again
// by the server; the page only hides what a viewer can't do anyway.
export default function PostView() {
  const { postId } = useParams();
  const navigate = useNavigate();
  const { user, dbProfile } = useAuth();
  const validId = ID_PATTERN.test(postId ?? '');

  const [post, setPost]         = useState(null);
  const [status, setStatus]     = useState(validId ? 'loading' : 'missing');
  const [comments, setComments] = useState([]);
  const [total, setTotal]       = useState(0);
  const [limit, setLimit]       = useState(PAGE);
  const [commentsState, setCommentsState] = useState('loading');
  const [replyTo, setReplyTo]   = useState(null);
  const [aura, setAura]         = useState(null);   // { comment, type }
  // Comments written here glow in; deleted ones fold away before they go
  const [fresh, setFresh]       = useState(() => new Set());
  const [leaving, setLeaving]   = useState(() => new Set());
  const composerRef = useRef(null);

  useEffect(() => {
    if (!validId) return undefined;
    let live = true;
    setStatus('loading');
    api.getPost(postId)
      .then(p => { if (live) { setPost(p); setStatus('ready'); } })
      .catch(() => { if (live) setStatus('missing'); });
    return () => { live = false; };
  }, [postId, validId]);

  const loadComments = useCallback(async (count) => {
    try {
      const data = await api.getComments(postId, count);
      setComments(data.comments ?? []);
      setTotal(data.total ?? 0);
      setCommentsState('ready');
    } catch {
      setCommentsState('error');
    }
  }, [postId]);

  useEffect(() => {
    if (status === 'ready') loadComments(limit);
  }, [status, limit, loadComments]);

  const charLimit = post?.groupId ? LIMIT_GROUP : LIMIT_GLOBAL;
  const shownTop = comments.length;

  async function addComment(text, parent = null) {
    const created = await api.createComment(postId, text, parent?.commentId ?? null);
    setFresh(set => new Set(set).add(created.commentId));
    recordEngagement(user?.userId, post, 'comment');
    setPost(p => ({ ...p, commentCount: (p.commentCount ?? 0) + 1 }));
    setTotal(t => t + 1);
    if (parent) {
      setComments(list => list.map(c => (c.commentId === parent.commentId
        ? { ...c, replies: [...(c.replies ?? []), created] } : c)));
      setReplyTo(null);
    } else {
      setComments(list => [created, ...list]);
    }
  }

  function removeComment(gone) {
    setLeaving(set => new Set(set).add(gone.commentId));
    setTimeout(() => {
      dropComment(gone);
      setLeaving(set => { const next = new Set(set); next.delete(gone.commentId); return next; });
    }, 320);
  }

  function dropComment(gone) {
    const removed = gone.parentCommentId ? 1 : 1 + (comments.find(c => c.commentId === gone.commentId)?.replies?.length ?? 0);
    setComments(list => (gone.parentCommentId
      ? list.map(c => (c.commentId === gone.parentCommentId
        ? { ...c, replies: c.replies.filter(r => r.commentId !== gone.commentId) } : c))
      : list.filter(c => c.commentId !== gone.commentId)));
    setPost(p => ({ ...p, commentCount: Math.max(0, (p.commentCount ?? 0) - 1) }));
    setTotal(t => Math.max(0, t - removed));
  }

  function auraDone(delta) {
    const id = aura.comment.commentId;
    const bump = c => (c.commentId === id ? { ...c, auraScore: (c.auraScore ?? 0) + delta } : c);
    setComments(list => list.map(c => ({ ...bump(c), replies: (c.replies ?? []).map(bump) })));
    setAura(null);
  }

  async function removePost(p) {
    await api.deletePost(p.postId);
    navigate('/', { replace: true });
  }

  const canRemovePost = post && (post.authorId === user?.userId || dbProfile?.isAdmin);

  return (
    <div className="mx-auto w-full max-w-2xl space-y-4 pb-10">
      <button onClick={() => (window.history.length > 1 ? navigate(-1) : navigate('/'))}
        className="inline-flex items-center gap-1.5 text-sm font-semibold text-[var(--text-muted)] hover:text-[var(--accent)]">
        <ArrowLeft size={16} /> Back
      </button>

      {status === 'loading' && <PostSkeleton />}
      {status === 'missing' && <NotFound />}

      {status === 'ready' && post && (
        <>
          {post.groupId && post.groupName && (
            <Link to={`/groups/${encodeURIComponent(post.groupId)}`}
              className="inline-flex items-center gap-1.5 text-xs font-semibold text-[var(--text-secondary)] hover:text-[var(--accent)]">
              Posted in {post.groupName}
            </Link>
          )}
          <PostCard
            key={post.postId}
            post={post}
            onRemove={canRemovePost ? removePost : undefined}
            onComment={() => composerRef.current?.focus()}
          />

          <section className="card p-4 sm:p-5" aria-labelledby="comments-heading">
            <h2 id="comments-heading" className="flex items-center gap-2 text-sm font-semibold text-[var(--text-primary)]">
              <MessageCircle size={16} className="text-[var(--accent)]" />
              Comments
              {total > 0 && <span className="text-[var(--text-muted)] font-normal">{total}</span>}
            </h2>

            <div className="mt-4 flex gap-3">
              <Avatar name={dbProfile?.displayName || dbProfile?.username} picKey={dbProfile?.profilePicKey} />
              <div className="flex-1">
                <Composer
                  inputRef={composerRef}
                  limit={charLimit}
                  placeholder="Add a comment..."
                  submitLabel="Comment"
                  onSubmit={text => addComment(text)}
                />
              </div>
            </div>

            <div className="mt-6 space-y-5">
              {commentsState === 'loading' && <CommentSkeleton />}
              {commentsState === 'error' && (
                <p className="text-sm text-[var(--text-muted)]">
                  Comments didn't load.{' '}
                  <button onClick={() => loadComments(limit)} className="font-semibold text-[var(--accent)]">Try again</button>
                </p>
              )}
              {commentsState === 'ready' && comments.length === 0 && (
                <p className="text-sm text-[var(--text-muted)]">No comments yet. Start the conversation.</p>
              )}

              {comments.map((comment, i) => (
                <div key={comment.commentId} className={`aura-fold ${leaving.has(comment.commentId) ? 'is-leaving' : ''}`}>
                <div className={fresh.has(comment.commentId) ? 'aura-comment-new' : 'aura-arrive'}
                  style={fresh.has(comment.commentId) ? undefined : { animationDelay: `${Math.min(i, 8) * 45}ms` }}>
                  <Comment comment={comment} post={post} onReply={setReplyTo}
                    onDeleted={removeComment} onAura={(c, type) => setAura({ comment: c, type })} />
                  {(comment.replies?.length > 0 || replyTo?.commentId === comment.commentId) && (
                    <div className="mt-3 ml-11 space-y-4 border-l border-[var(--border)] pl-4">
                      {comment.replies?.map(reply => (
                        <div key={reply.commentId} className={`aura-fold ${leaving.has(reply.commentId) ? 'is-leaving' : ''}`}>
                          <div className={fresh.has(reply.commentId) ? 'aura-comment-new' : ''}>
                            <Comment comment={reply} post={post} isReply
                              onDeleted={removeComment} onAura={(c, type) => setAura({ comment: c, type })} />
                          </div>
                        </div>
                      ))}
                      {replyTo?.commentId === comment.commentId && (
                        <Composer
                          autoFocus
                          limit={charLimit}
                          placeholder={`Reply to @${comment.authorUsername}...`}
                          submitLabel="Reply"
                          onSubmit={text => addComment(text, comment)}
                          onCancel={() => setReplyTo(null)}
                        />
                      )}
                    </div>
                  )}
                </div>
                </div>
              ))}

              {commentsState === 'ready' && shownTop >= limit && limit < MAX_PAGE && (
                <button onClick={() => setLimit(l => Math.min(MAX_PAGE, l + PAGE))}
                  className="w-full rounded-xl py-2 text-sm font-semibold text-[var(--accent)] hover:bg-[var(--accent-subtle)]">
                  Show more comments
                </button>
              )}
            </div>
          </section>
        </>
      )}

      {aura && post && (
        <AuraModal post={post} comment={aura.comment} type={aura.type}
          onSuccess={auraDone} onClose={() => setAura(null)} />
      )}
    </div>
  );
}
